export const HISTORICAL = EPOCHS.filter((e) => !e.forecast);
export const FORECASTS = EPOCHS.filter((e) => e.forecast);

export function epochAt(year) {
  // Nearest epoch by distance to its span (0 inside the span).
  let best = null, bestD = Infinity;
  for (const e of EPOCHS) {
    const d = year < e.span[0] ? e.span[0] - year : year > e.span[1] ? year - e.span[1] : 0;
    if (d < bestD) { bestD = d; best = e; }
  }
  return { epoch: best, distance: bestD };
}

